def number(value):
    if value in (None, '', '-'):
        return None
    if value == 'TR':
        return 0
    return float(value)


def main(path: str) -> None:
    sheet = openpyxl.load_workbook(path, read_only=True).active
    bls = {}
    for index, row in enumerate(sheet.iter_rows(values_only=True)):
        if index:
            bls[row[0]] = row
    rows = json.loads(TARGET.read_text(encoding='utf-8'))
    known = {row['code'] for row in rows}
    for row in rows:
        selected = SELECTION.get(row['code'])
        row['aliases'] = ALIASES.get(row['code'], selected[4] if selected else [])
    for code, (category, label, grams, zero, aliases) in SELECTION.items():
        if code in known:
            continue
        source = bls[code]
        rows.append({
            'code': code,
            'name': source[1],
            'category': category,
            'per100': {name: number(source[column]) for name, column in COLUMNS.items()},
            'zero': zero,
            'portion': {'label': label, 'grams': grams},
            'aliases': aliases,
        })
    missing = [row['code'] for row in rows if row['code'] not in DISPLAY_NAMES]
    if missing:
        raise SystemExit(f'Anzeigename fehlt für: {", ".join(missing)}')
    for row in rows:
        row['blsName'] = bls[row['code']][1]
        row['name'] = DISPLAY_NAMES[row['code']]
    TARGET.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{len(rows)} Lebensmittel geschrieben.')


if __name__ == '__main__':
    main(sys.argv[1])
